/**
 * PRD 9.4 bonus: packages the agent for other agent platforms from the SAME sources the app uses
 * (prompt, knowledge and tools), so the module can never diverge from the application.
 *
 *   bun scripts/build-modulo.ts
 */
import { mkdir, writeFile } from "node:fs/promises"
import { join, resolve } from "node:path"

const root = resolve(import.meta.dir, "..")
const out = join(root, "modulo")

const prompt = await Bun.file(join(root, "app/agent/prompt.md")).text()
const knowledge = await Bun.file(join(root, "app/agent/src/knowledge/ordenes-compra.md")).text()

const agentMd = `---
description: Prepara y crea órdenes de compra en SAP aplicando los controles RC1–RC10; pide confirmación humana ante excepciones.
mode: primary
permission:
  edit: deny
  bash: deny
---

${prompt.trim()}
`

const skillMd = `---
name: ordenes-compra
description: Conocimiento del proceso de órdenes de compra de Periferia (actores, controles RC1–RC10, OC retroactivas, glosario SAP).
---

${knowledge.trim()}
`

const toolsTs = `/**
 * Generated by scripts/build-modulo.ts — do not edit.
 * The same oc_* tools used by the app (single source: app/contracts/src/tools).
 * They need an OcPort: in process (backend) or over HTTP (OcHttpClient from @oc/agent).
 */
export * from "../../app/contracts/src/tools/index"
`

await mkdir(join(out, "tools"), { recursive: true })
await mkdir(join(out, "skill/ordenes-compra"), { recursive: true })
await writeFile(join(out, "agent.md"), agentMd)
await writeFile(join(out, "skill/ordenes-compra/SKILL.md"), skillMd)
await writeFile(join(out, "tools/oc.ts"), toolsTs)
console.log("modulo/ generated: agent.md, tools/oc.ts, skill/ordenes-compra/SKILL.md")
